"use client";

import type { ReactNode } from "react";

/**
 * DockedChat — টেস্টার পুরো মঞ্চ নিয়ে।
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * উচ্চতা `100dvh-18rem`: হেডার (৬৪px) + এই পেজের শিরোনাম, মোড-সুইচার, লেআউট
 * টগল আর নিচের ফাঁকা জায়গা বাদ দিয়ে যা থাকে। `dvh` (svh/vh নয়) কারণ মোবাইলে
 * অ্যাড্রেস বার সরে গেলে `vh` মেপে ভুল হয়, আর ইনপুট বারটা স্ক্রিনের নিচে
 * চলে যায়।
 *
 * ⚠️ চ্যাট অ্যাপ সরুই ভালো (`max-w-2xl`): ফুল-উইথ লাইনে প্রশ্নের শেষ আর উত্তরের
 *    শুরু এক লাইনে দুই প্রান্তে সরে যায়, চোখকে লাফাতে হয়।
 */
export function DockedChat({ children }: { children: ReactNode }) {
  return (
    <div className="mx-auto h-[calc(100dvh-18rem)] min-h-[420px] w-full max-w-2xl">
      {children}
    </div>
  );
}
