/**
 * Billing cycle — DRIPLARE AI (১৫.৭)
 * ─────────────────────────────────────────────────────────────────────────────
 * একটি plan-এর মেয়াদ কত দিন, আর নতুন মেয়াদ কোথা থেকে গোনা শুরু হয় — কেবল এই
 * দুটি প্রশ্নের উত্তর এখানে। `lib/domain`-এ রাখা হয়েছে কারণ এটি বিশুদ্ধ গণিত,
 * কোনো DB নেই, আর একটি ভুল দিন-গণনার ফল সরাসরি টাকা (merchant হয় আগেভাগে
 * বন্ধ হয়ে যান, নয় বিনা পয়সায় চলে যান) — তাই এটি test-যোগ্য হওয়া দরকার।
 *
 * ⚠️ **এই ফাইলটি ইচ্ছাকৃতভাবে leaf।** এর কোনো runtime import নেই, তাই
 *    `admin-credits.ts` (grant), `reset-eligibility.ts` (cron) আর payment route
 *    — তিনজনই এটি পড়তে পারে কোনো শৃঙ্খল তৈরি না করে।
 */

/**
 * কেনাকাটার ধরন।
 *
 * ⚠️ টাইপটি এখানে (এবং `pricing-catalogue.ts`-এ নয়) থাকার কারণ: "মাসিক/বার্ষিক"
 *    একটি **সময়ের** ধারণা, দামের নয়। দামের ক্যাটালগ শুধু এই ধরনটি ব্যবহার করে
 *    (বার্ষিক দাম বসাতে), অর্থাৎ নির্ভরতার দিকটি একমুখী — ক্যাটালগ → এখানে।
 *    উল্টো দিকে রাখলে সময়ের নিয়ম দামের JSON-এর উপর নির্ভর করত, যা অর্থহীন।
 */
export type BillingCycle = "monthly" | "yearly";

/**
 * মাসিক চক্রের দৈর্ঘ্য।
 *
 * ⚠️ এই ৩০-ই আগে কোডের ৩+ জায়গায় হাতে লেখা ছিল (`admin-credits.ts`-এ দুইবার,
 *    reset path-এ)। এক জায়গায় আনার কারণ কোনো সৌন্দর্য নয়: বার্ষিক plan যোগ
 *    করার মুহূর্তে যদি ৩০ আর ৩৬৫ আলাদা আলাদা জায়গায় থাকত, তবে কোথাও একটা
 *    থেকে যেত — আর একটি merchant-এর credit মাসের বদলে বছরে একবার নবায়ন হত।
 */
export const CYCLE_DAYS = 30;

/**
 * বার্ষিক চক্রের দৈর্ঘ্য — ৩৬৫, ১২ × ৩০ = ৩৬০ নয়।
 *
 * ⚠️ **এই ৫ দিনের ফারাকটি ইচ্ছাকৃত এবং গুরুত্বপূর্ণ।** দুটি সংখ্যার কাজ আলাদা:
 *
 *  - `CYCLE_DAYS` (৩০) = কত দিন পরপর **credit** নবায়ন হয়, অর্থাৎ গ্রাহক যা পান।
 *  - `YEARLY_DAYS` (৩৬৫) = কত দিন পর্যন্ত **সেবার মেয়াদ**, অর্থাৎ গ্রাহক যা কিনেছেন।
 *
 * ৩৬০ নিলে একজন বার্ষিক গ্রাহকের মেয়াদ প্রতি বছর ৫ দিন কুঁচকে যেত — ৭২ বছরে
 * একটি পুরো মাস। আর ৩০-ই ব্যবহার করলে বার্ষিক কিনে কোন লাভই নেই: মেয়াদ ১২ বার
 * শেষ হয়ে প্রতিবার নবায়ন চাইত, অর্থাৎ ঠিক যা বার্ষিক বিক্রয়ে এড়াতে চাই।
 *
 * ⚠️ তাই বার্ষিক plan-এ `planExpiresAt` ৩৬৫ দিন যায়, কিন্তু `creditsResetDate`
 *    ৩০ দিনেই থাকে। **Credit মাসে মাসে আসে, একবারে নয়** (ব্যবহারকারীর সিদ্ধান্ত,
 *    ১৫.৭): একবারে ১২ মাসের credit দিলে একজন merchant এক মাসে সেটি জ্বালিয়ে ১১
 *    মাস খালি হাতে বসে থাকতেন — অথচ তিনি টাকা দিয়েছেন।
 */
export const YEARLY_DAYS = 365;

/** একটি cycle-এর দৈর্ঘ্য দিনে। */
export function cycleDays(cycle: BillingCycle): number {
  return cycle === "yearly" ? YEARLY_DAYS : CYCLE_DAYS;
}

/**
 * নতুন মেয়াদ — **আগের মেয়াদ শেষ হলে সেখান থেকে, নইলে এখন থেকে**।
 *
 * ⚠️ **কেন `now + period` নয় — এটিই এই ফাংশনের পুরো অস্তিত্বের কারণ।**
 *    আগে ([`admin-credits.ts`](lib/services/admin-credits.ts)-এ) নিয়মটি ছিল
 *    `planExpiresAt = now + 30`। অর্থাৎ যে merchant ২৫তম দিনে টাকা দিতেন, তাঁর
 *    ৫ দিন জ্বলে যেত; ২৯তম দিনে দিলে ২৯। তাঁর কাছ থেকে একই টাকা নিয়ে কম দিন
 *    দেওয়া — অর্থাৎ একটি নীরব খারাপ চুক্তি, যার সূত্র কেউ কখনো পেতেন না।
 *
 *    `max(now, current)` নিলে দিনগুলো **জমে** (stack হয়): ২৫তম দিনে দিলে
 *    ২৫ + ৩০ = ৫৫তম দিন পর্যন্ত। গ্রাহকের প্রতি ন্যায্য, আর মোটের উপর আমাদের
 *    কোনো ক্ষতি নেই — আমরা কেবল সেই দিনগুলোই দিচ্ছি যেগুলোর জন্য টাকা নিয়েছি।
 *
 * ⚠️ **`current` যদি অনেক পুরনো হয়** (যেমন ৬ মাস আগে মেয়াদ শেষ, এখন নবায়ন):
 *    `max` তখন `now`-ই নেয়, ফলে তিনি অতীত থেকে জমতে থাকা দিন পেয়ে যান না।
 *    এটি ইচ্ছাকৃত — নইলে একজন ১ বছর পরে ফিরে এসে ১ বছর মেয়াদ যোগ করে ফেলতেন।
 *
 * @param now    এখনকার মুহূর্ত (পরীক্ষায় বসানোর জন্য প্যারামিটার, `Date.now()` নয়)
 * @param cycle  মাসিক, নাকি বার্ষিক
 * @param current বর্তমান মেয়াদ; `null` মানে আজ পর্যন্ত কোনো মেয়াদ বসেনি
 */
export function resolvePlanExpiry(
  now: Date,
  cycle: BillingCycle,
  current: Date | null
): Date {
  // ⚠️ একটি অবৈধ `Date` (Invalid Date) `>`-তে সবসময় false দেয়, ফলে সেটি নীরবে
  //    `now`-তে নেমে আসত — অর্থাৎ ভাঙা ডেটা একটি ভুল মেয়াদ বানাত। তাই আলাদা
  //    করে বাদ দেওয়া হয়: অবৈধ হলে "মেয়াদ নেই" ধরা হয়, যা নিরাপদ দিক।
  const base =
    current && !Number.isNaN(current.getTime()) && current.getTime() > now.getTime()
      ? new Date(current)
      : new Date(now);

  // ⚠️ `setDate()` ব্যবহার করা হয় মিলিসেকেন্ড যোগ করার বদলে — কারণ বিদ্যমান
  //    কোডও তাই করে, আর `setDate` স্থানীয় সময়ের দিন-সীমা মানে, যা একজন
  //    merchant-এর কাছে "একই সময়ে পরের মাসে" বলতে যা বোঝায়।
  base.setDate(base.getDate() + cycleDays(cycle));
  return base;
}

/**
 * অজানা ইনপুট → নিরাপদ cycle।
 *
 * ⚠️ **ডিফল্ট `monthly`, এবং এই ডিফল্টটি নিরাপদ দিক:** একটি ভাঙা/টাইপো মান
 *    (`"Yearly"`, `"annual"`, `true`) যদি বার্ষিক ধরা হত, তবে একটি ৳৯৯৯-এর
 *    মাসিক পেমেন্ট ৩৬৫ দিনের মেয়াদ দিত — অর্থাৎ ১২ মাসের সেবা এক মাসের দামে।
 *    উল্টো দিকে ভুল করলে আমরা ৩০ দিন দিই, যা ওই পেমেন্টের ন্যায্য মূল্য।
 */
export function normalizeCycle(value: unknown): BillingCycle {
  return value === "yearly" ? "yearly" : "monthly";
}
